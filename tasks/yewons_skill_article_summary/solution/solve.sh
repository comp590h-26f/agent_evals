Urban trees depend on healthy soil that gives their roots air, water, nutrients, and room to grow. Compaction from construction and foot traffic reduces pore space, causing rain to run off and leaving roots short of oxygen and moisture even when trees are watered. Soil organisms recycle nutrients, while organic mulch feeds this community, limits evaporation, and protects the surface. Preserving uncompacted soil, keeping heavy traffic away from roots, and providing enough water help trees survive dry periods and keep shading city streets.
